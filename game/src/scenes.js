// kinds: removed, extra, color, flip and detail (a swapped parameter such as a
// clock's hands, a bottle's fill, a plant's leaf count or a telescope's tilt).

/** Compact object builder: o('gear1', 'gear', x, y, { c, n, s }). */
function o(id, kind, x, y, opts = {}) {
  return { id, kind, x, y, s: 1, ...opts };
}

/** Compact difference builder; (x, y) is the object's centre, r its ring size. */
function d(id, obj, type, x, y, note, extra = {}) {
  return { id, obj, type, x, y, r: 30, note, ...extra };
}

